#pragma once

// subplane core message types.
//
// TickHeader is BOTH the in-agent routing header and the on-ring record
// header that apps read. It is the one ABI shared with applications, so it is
// versioned (RECORD_VERSION) and its layout is frozen by static_asserts.

#include <cstddef>
#include <cstdint>
#include <cstring>
#include <type_traits>

namespace subplane {

// Bumped whenever TickHeader or a control event payload changes layout.
// Readers refuse rings whose record_version differs.
inline constexpr uint32_t RECORD_VERSION = 1;

using SymbolId    = uint32_t;
using VenueId     = uint16_t;
using PartitionId = uint16_t;
using TimestampNs = uint64_t; // nanoseconds since Unix epoch (CLOCK_REALTIME)

// What kind of record this is.
enum class Kind : uint8_t {
    DATA          = 0, // market data message; payload = original SBE bytes
    BUS_ADMIN     = 1, // admin message from the bus; payload = original SBE bytes
    AGENT_CONTROL = 2, // event generated by subplane; payload = control POD
    PAD           = 3, // ring padding at wrap; no payload meaning
};

// Wire format of a DATA/BUS_ADMIN payload.
enum class WireFormat : uint8_t {
    UNKNOWN = 0,
    SBE     = 30,
    DBN     = 31, // Databento Binary Encoding (fixed 16-byte record header)
    FLATBUFFERS = 32, // whole FlatBuffer, size prefix included when the bus uses one
};

// Data message types (msg_type < 0x80). Mapped from SBE templateId by config.
enum class MsgType : uint8_t {
    UNKNOWN       = 0,
    TRADE         = 1,
    QUOTE         = 2,
    BOOK_UPDATE   = 3,
    BOOK_SNAPSHOT = 4,
    OHLCV         = 5,
    STATUS        = 6,
    // INTENT: instrument definitions get their own type so the last-value cache
    // keeps them in their own slot; sharing STATUS made each overwrite the other.
    DEFINITION    = 7,
    // 0x80.. are control codes, see ControlCode.
};
inline constexpr uint8_t MSG_TYPE_DATA_MAX = 0x7F;

// Control codes carried in TickHeader::msg_type when kind != DATA.
// 0x80-0x9F: bus admin (payload = raw SBE bytes).
// 0xA0-0xBF: agent control (payload = POD from control_events.h).
enum class ControlCode : uint8_t {
    BUS_HEARTBEAT       = 0x80,
    BUS_SEQ_RESET       = 0x81,
    BUS_SNAPSHOT_START  = 0x82,
    BUS_SNAPSHOT_END    = 0x83,
    BUS_TRADING_STATUS  = 0x84,

    GAP_DETECTED        = 0xA0,
    PARTITION_DEGRADED  = 0xA1,
    PARTITION_RECOVERED = 0xA2,
    FILTER_RELOADED     = 0xA3,
    AGENT_RESTARTED     = 0xA4,
    SESSION_CLOSING     = 0xA5,
    SYMBOL_MAPPED       = 0xA6,
    TRANSPORT_DOWN      = 0xA7,
    TRANSPORT_UP        = 0xA8,

    PAD                 = 0xFE,
};

// Flags bits in TickHeader::flags.
inline constexpr uint8_t FLAG_LVC_TRUNCATED   = 0x01; // LVC stored header only (payload too large)
inline constexpr uint8_t FLAG_SNAPSHOT_ORIGIN = 0x02; // record came from a SNAPSHOT reply, not the live ring

// Routing + record header. Exactly one cache line.
//
// INTENT: fixed 64 bytes, trivially copyable, no pointers, no strings. It is
// memcpy'd onto shared-memory rings and read by foreign processes. Changing
// any field is an ABI change: bump RECORD_VERSION. The symbol *name* is
// deliberately absent; apps key by symbol_id and learn names via the
// SYMBOL_MAPPED control event or the control channel HELLO.
struct alignas(64) TickHeader {
    uint64_t seq_tag;        // ring: absolute byte position of this record (written last, release). 0 elsewhere.
    uint64_t sequence;       // bus sequence number, per partition. 0 if the bus has none.
    uint64_t exchange_ts;    // ns since epoch from the mapped schema field. 0 if unmapped.
    uint64_t ingest_ts;      // ns since epoch, packet receive time. Never 0 on a delivered record (INV-006).
    uint32_t symbol_id;      // dense interned id (or passthrough per config).
    uint32_t payload_len;    // bytes following this header.
    uint16_t template_id;    // SBE templateId (0 for agent control).
    uint16_t schema_id;      // SBE schemaId.
    uint16_t schema_version; // SBE version.
    uint16_t venue_id;       // interned venue id, 0 if unmapped.
    uint16_t partition_id;   // activation (partition) that produced this record.
    uint8_t  msg_type;       // MsgType for DATA; ControlCode otherwise.
    uint8_t  kind;           // Kind.
    uint8_t  wire_format;    // WireFormat.
    uint8_t  flags;          // FLAG_*.
    uint8_t  reserved[10];   // zero.
};

static_assert(sizeof(TickHeader) == 64, "TickHeader must be exactly one cache line");
static_assert(alignof(TickHeader) == 64, "TickHeader must be cache-line aligned");
static_assert(std::is_trivially_copyable_v<TickHeader>, "TickHeader must be trivially copyable");
static_assert(offsetof(TickHeader, seq_tag) == 0);
static_assert(offsetof(TickHeader, symbol_id) == 32);
static_assert(offsetof(TickHeader, msg_type) == 50);
static_assert(offsetof(TickHeader, reserved) == 54);

inline constexpr bool is_data(const TickHeader& h) noexcept {
    return h.kind == static_cast<uint8_t>(Kind::DATA);
}
inline constexpr bool is_control(const TickHeader& h) noexcept {
    return h.kind == static_cast<uint8_t>(Kind::AGENT_CONTROL) ||
           h.kind == static_cast<uint8_t>(Kind::BUS_ADMIN);
}

// Zero-initialised header with the given kind/code. Convenience for control events.
inline TickHeader make_control_header(ControlCode code, PartitionId partition,
                                      TimestampNs ingest_ts, uint32_t payload_len) noexcept {
    TickHeader h{};
    h.ingest_ts    = ingest_ts;
    h.payload_len  = payload_len;
    h.partition_id = partition;
    h.msg_type     = static_cast<uint8_t>(code);
    h.kind         = static_cast<uint8_t>(code == ControlCode::PAD ? Kind::PAD
                                          : static_cast<uint8_t>(code) < 0xA0 ? Kind::BUS_ADMIN
                                                                              : Kind::AGENT_CONTROL);
    return h;
}

} // namespace subplane
